void load()
{
    std::string newLang = config::get().language;
    auto* newTable = (newLang == "en") ? nullptr : new std::unordered_map<std::string, const char*>();
    if (newTable)
    {
        if (newLang == "fr")
        {
            newTable->reserve(sizeof(kFr) / sizeof(kFr[0]) * 2);
            for (const auto& e : kFr)
                (*newTable)[e.en] = e.val;
        }
        else if (newLang == "es-es")
        {
            newTable->reserve(sizeof(kEsEs) / sizeof(kEsEs[0]) * 2);
            for (const auto& e : kEsEs)
                (*newTable)[e.en] = e.val;
        }
        else if (newLang == "pt-br")
        {
            newTable->reserve(sizeof(kPtBr) / sizeof(kPtBr[0]) * 2);
            for (const auto& e : kPtBr)
                (*newTable)[e.en] = e.val;
        }
        else if (newLang == "ru")
        {
            newTable->reserve(sizeof(kRu) / sizeof(kRu[0]) * 2);
            for (const auto& e : kRu)
                (*newTable)[e.en] = e.val;
        }
        else if (newLang == "el")
        {
            newTable->reserve(sizeof(kEl) / sizeof(kEl[0]) * 2);
            for (const auto& e : kEl)
                (*newTable)[e.en] = e.val;
        }
        else // "es" (default)
        {
            newTable->reserve(sizeof(kEs) / sizeof(kEs[0]) * 2);
            for (const auto& e : kEs)
                (*newTable)[e.en] = e.val;
        }
    }

    std::unordered_map<std::string, const char*>* oldTable = nullptr;
    {
        std::lock_guard<std::mutex> lock(g_mutex);
        g_lang = newLang;
        oldTable = g_table;
        g_table = newTable;
    }
    delete oldTable;
}

const std::string& lang()
{
    return g_lang;
}

