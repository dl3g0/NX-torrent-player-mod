void load()
{
    g_lang = config::get().language;
    if (g_lang == "en")
        return;

    delete g_table;
    g_table = new std::unordered_map<std::string, const char*>();
    if (g_lang == "fr")
    {
        g_table->reserve(sizeof(kFr) / sizeof(kFr[0]) * 2);
        for (const auto& e : kFr)
            (*g_table)[e.en] = e.val;
    }
    else if (g_lang == "es-es")
    {
        g_table->reserve(sizeof(kEsEs) / sizeof(kEsEs[0]) * 2);
        for (const auto& e : kEsEs)
            (*g_table)[e.en] = e.val;
    }
    else if (g_lang == "pt-br")
    {
        g_table->reserve(sizeof(kPtBr) / sizeof(kPtBr[0]) * 2);
        for (const auto& e : kPtBr)
            (*g_table)[e.en] = e.val;
    }
    else if (g_lang == "ru")
    {
        g_table->reserve(sizeof(kRu) / sizeof(kRu[0]) * 2);
        for (const auto& e : kRu)
            (*g_table)[e.en] = e.val;
    }
    else // "es" (default)
    {
        g_table->reserve(sizeof(kEs) / sizeof(kEs[0]) * 2);
        for (const auto& e : kEs)
            (*g_table)[e.en] = e.val;
    }
}

const std::string& lang()
{
    return g_lang;
}

