const char* tr(const char* en)
{
    if (!en)
        return en;
    std::lock_guard<std::mutex> lock(g_mutex);
    if (!g_table)
        return en;
    auto it = g_table->find(en);
    return it == g_table->end() ? en : it->second;
}

